namespace Novamira\Pro\Abilities\WPBakery;

use WP_Error;

if (!defined('ABSPATH')) {
    exit();
}

/**
 * Ability: Get WPBakery per-post settings.
 *
 * WPBakery stores a handful of meta keys on each post it owns:
 *  - `_wpb_vc_js_status`              : 'true' when the post is a WPBakery
 *                                       page (drives the "Edit with WPBakery"
 *                                       admin link and the frontend asset
 *                                       loader).
 *  - `_wpb_post_custom_css`           : page-level custom CSS textarea.
 *  - `_wpbakery_shortcodes_custom_css`: CSS WPBakery generates from element
 *                                       Design Options.
 */

wp_register_ability('novamira/wpbakery-get-settings', [
    'label' => __('Get WPBakery Settings', domain: 'novamira-pro'),
    'description' => __(
        'Reads the WPBakery-owned meta on a post: wpbakery_edited flag (mirrors _wpb_vc_js_status), page-level custom_css (free-form CSS the user authors, postmeta _wpb_post_custom_css — this is what most agents care about), and shortcodes_custom_css (auto-generated by WPBakery from every element\'s `css` Design Options att, rebuilt on save — read-mostly, rarely written). Use this to verify a post was correctly marked as WPBakery-edited before opening the editor, or to read the current page-level CSS before patching it.',
        domain: 'novamira-pro',
    ),
    'category' => 'wpbakery',
    'input_schema' => [
        'type' => 'object',
        'properties' => [
            'post_id' => [
                'type' => 'integer',
                'description' => 'ID of the post to read settings from.',
            ],
        ],
        'required' => ['post_id'],
        'additionalProperties' => false,
    ],
    'output_schema' => [
        'type' => 'object',
        'properties' => [
            'post_id' => ['type' => 'integer'],
            'wpbakery_edited' => ['type' => 'boolean'],
            'custom_css' => ['type' => 'string'],
            'shortcodes_custom_css' => ['type' => 'string'],
        ],
        'required' => ['post_id', 'wpbakery_edited', 'custom_css', 'shortcodes_custom_css'],
    ],
    'execute_callback' => 'Novamira\\Pro\\Abilities\\WPBakery\\wpbakery_get_settings',
    'permission_callback' => 'novamira_permission_callback',
    'meta' => [
        'show_in_rest' => true,
        'mcp' => ['public' => true],
        'annotations' => [
            'instructions' => 'Reads WPBakery per-post meta. wpbakery_edited=true means _wpb_vc_js_status is set to the literal string "true" on the post — required for the "Edit with WPBakery" admin link to appear and for the frontend asset bundle to load. Returns wpbakery_not_found when the post does not exist.',
            'readonly' => true,
            'destructive' => false,
            'idempotent' => true,
        ],
    ],
]);

/**
 * @param array{post_id: int} $input
 * @return array{
 *     post_id: int,
 *     wpbakery_edited: bool,
 *     custom_css: string,
 *     shortcodes_custom_css: string,
 * }|WP_Error
 */
function wpbakery_get_settings(array $input): array|WP_Error
{
    $post_id = $input['post_id'];
    if ($post_id <= 0 || get_post($post_id) === null) {
        return new WP_Error('wpbakery_not_found', sprintf(
            /* translators: %d: post ID. */
            __('Post %d not found.', domain: 'novamira-pro'),
            $post_id,
        ));
    }

    /** @var mixed $edited_raw */
    $edited_raw = get_post_meta($post_id, key: WPB_META_EDITED, single: true);
    /** @var mixed $custom_css_raw */
    $custom_css_raw = get_post_meta($post_id, key: WPB_META_CUSTOM_CSS, single: true);
    /** @var mixed $shortcodes_css_raw */
    $shortcodes_css_raw = get_post_meta($post_id, key: WPB_META_SHORTCODES_CSS, single: true);

    return [
        'post_id' => $post_id,
        'wpbakery_edited' => is_string($edited_raw) && $edited_raw === 'true',
        'custom_css' => is_string($custom_css_raw) ? $custom_css_raw : '',
        'shortcodes_custom_css' => is_string($shortcodes_css_raw) ? $shortcodes_css_raw : '',
    ];
}
